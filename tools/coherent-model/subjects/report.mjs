// Writes docs/subject-reclassification.md from the model manifest and classification.mjs: the
// subjects, what each will hold, the merge families, the specializations kept, the application
// detail that leaves the model, and every current concept's fate. Unclassified concepts fail.
//   node tools/coherent-model/subjects/report.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { SUBJECTS, NEW_CONCEPTS, codeOf } from "./classification.mjs";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const model = JSON.parse(fs.readFileSync(path.join(repo, "model", "model.json"), "utf8"));
// The plan was made against the domain layout; once migrated, docs/subject-reclassification.md is its record.
if (!model.domains) { console.log("The model is already organized by subject: docs/subject-reclassification.md records the reclassification."); process.exit(0); }
const subjectName = new Map(SUBJECTS.map(([id, name]) => [id, name]));
const domainOf = (p) => p.split("/")[2];
const domainTitle = new Map([...model.domains.map((d) => [d.path.split("/")[2], d.name]), ["administration", "Administration"]]);
const patternOf = { "crane-rental": "crane-rental-orchestration", "e-commerce": "e-commerce", "equipment-service": "equipment-service", "financial-services": "financial-services",
  "health-care": "health-care", insurance: "insurance", "legacy-conversion": "legacy-conversion", manufacturing: "manufacturing", "physical-therapy": "physical-therapy-clinic",
  "professional-services": "professional-services", telecommunications: "telecommunications", travel: "travel" };

const rows = [], missing = [];
for (const c of model.concepts) {
  const domain = domainOf(c.path), code = codeOf(domain, c.name);
  if (!code) { missing.push(`${domain} / ${c.name}`); continue; }
  const [kind, subject, target, rename] = code.split(":");
  rows.push({ domain, name: rename || c.name, was: rename ? c.name : null, path: c.path, kind, subject: subject || null, target: target || null, specializes: c.specializes });
}
for (const [subject, name, meaning, area] of NEW_CONCEPTS) rows.push({ domain: "administration", name, path: null, kind: "N", subject, target: null, meaning, area });
if (missing.length) { console.error(`Unclassified concepts (${missing.length}):\n  ${missing.join("\n  ")}`); process.exit(1); }

const count = (k) => rows.filter((r) => r.kind === k).length;
// What each subject will hold: kept concepts (C, S, K) and one common concept per merge name.
const holds = new Map(SUBJECTS.map(([id]) => [id, new Map()]));
for (const r of rows) {
  if (!r.subject) continue;
  const name = r.kind === "M" ? r.target : r.name;
  const entry = holds.get(r.subject).get(name) || { name, kinds: new Set(), members: [] };
  entry.kinds.add(r.kind);
  entry.members.push(r);
  holds.get(r.subject).set(name, entry);
}
const label = (r) => `${r.was ? `${r.was}, renamed ${r.name}` : r.name} (${domainTitle.get(r.domain) || r.domain})`;
const lines = [
  "# Subject reclassification", "",
  "<!-- Generated by tools/coherent-model/subjects/report.mjs from classification.mjs. Edit the classification, then regenerate. -->", "",
  "The canonical model is reorganized by **subject**: an area of reusable business knowledge with one coherent responsibility (the *subject data areas* of the Data Model Resource Book). **Industries** (health care, crane rental, travel, …) are industry patterns: they select and explain subjects, and name what an application typically adds. The model carries **common models only**; an application adds its own concepts in its own Specs.", "",
  "Every current concept is classified:", "",
  "| Fate | Meaning | Concepts |", "|---|---|---|",
  `| **Common** | kept as it is, in its subject | ${count("C")} |`,
  `| **Merged** | the same concept under another name in another industry: merged into one common concept; its name becomes an alias | ${count("M")} |`,
  `| **Specialization** | a variation many applications of an industry need, adding reusable knowledge: kept, specializing a common concept | ${count("S")} |`,
  `| **Industry subject** | kept in a subject one industry owns (health care, insurance, financial accounts, networks, production, travel) | ${count("K")} |`,
  `| **Application detail** | needed by one kind of business only, or adding nothing an application could not define: leaves the model, named in one line in its industry pattern | ${count("A")} |`,
  `| **Modeling pattern** | a data-migration concern, not business knowledge: moves to modeling-patterns/ | ${count("P")} |`,
  `| **New** | a common concept Administration only named as a candidate: defined now | ${count("N")} |`, "",
  `From ${rows.length - count("N")} concepts in ${new Set(rows.filter((r) => r.kind !== "N").map((r) => r.domain)).size} domains, plus ${count("N")} new, to **${[...holds.values()].reduce((n, m) => n + m.size, 0)} concepts in ${SUBJECTS.length} subjects**.`, "",
  "## Subjects", "",
  "| Subject | Responsibility | Concepts |", "|---|---|---|",
  ...SUBJECTS.map(([id, name, what]) => `| **${name}** (\`${id}\`) | ${what} | ${holds.get(id).size} |`), "",
];
for (const [id, name] of SUBJECTS) {
  const entries = [...holds.get(id).values()].sort((a, b) => a.name.localeCompare(b.name));
  lines.push(`### ${name}`, "", "| Concept | From |", "|---|---|");
  for (const e of entries) {
    const kept = e.members.filter((r) => r.kind !== "M");
    const merged = e.members.filter((r) => r.kind === "M");
    const spec = kept.find((r) => r.kind === "S");
    const from = [
      ...kept.map((r) => r.kind === "N" ? `**new** (Administration · ${r.area}): ${r.meaning}` : `${label(r)}${r.kind === "S" ? ` — specializes ${r.target}` : r.kind === "K" ? " — industry subject" : ""}`),
      ...(merged.length ? [`merged: ${merged.map(label).join(", ")}`] : []),
    ].join("; ");
    lines.push(`| ${e.name}${kept.length ? "" : " *(new common name)*"} | ${from} |`);
  }
  lines.push("");
}
// Merge families with more than one source industry: the common shape found across industries.
const families = [...holds.values()].flatMap((m) => [...m.values()]).filter((e) => new Set(e.members.map((r) => r.domain)).size > 1)
  .sort((a, b) => b.members.length - a.members.length || a.name.localeCompare(b.name));
lines.push("## Merge families", "", "Concepts found in more than one domain, merged into one common concept. These are the common shapes across industries.", "",
  "| Common concept | Subject | Members |", "|---|---|---|",
  ...families.map((e) => `| **${e.name}** | ${subjectName.get(e.members[0].subject)} | ${e.members.map(label).join(", ")} |`), "");
// Application detail, by industry pattern.
const detail = rows.filter((r) => r.kind === "A");
lines.push("## Application detail, named in the industry patterns", "", "These leave the model. Each industry pattern gains a short *Concepts applications typically add* list naming them, so the knowledge is not lost, but nobody maintains their definitions.", "");
for (const d of [...new Set(detail.map((r) => r.domain))]) {
  lines.push(`- **${domainTitle.get(d) || d}** ([pattern](../industry-patterns/${patternOf[d] || d}.md)): ${detail.filter((r) => r.domain === d).map((r) => r.name).join(", ")}.`);
}
lines.push("");
// Modeling pattern.
const moved = rows.filter((r) => r.kind === "P");
lines.push("## To modeling patterns", "", `Legacy conversion is a modeling concern (source structures, mappings, migration runs, cutover), not a subject. Its ${moved.length} migration concepts move to a *Data Migration* modeling pattern; its identity, ownership, and data-quality concepts join Information Governance.`, "",
  `${moved.map((r) => r.name).join(", ")}.`, "");
// Administration: its candidates, now defined, and its folder removed.
lines.push("## Administration", "", "`model/domains/administration/` held only candidate lists for Organization, Human Resources, Facilities, and Accounting: named, never defined, and not in the model. They are common to every business, so they join the subjects: organization structure in Parties and Roles, the workforce and the ledger as subjects of their own (Workforce, Accounting), facilities in Locations and Sites. Concepts the model already had take their place (Worker from Technician and Professional, Qualification, Skill, Time Entry; Ledger Account, Journal Entry, Posting Batch from Financial Services; Facility; Invoice, Payment, Expense, Customer Account). The rest are defined now:", "",
  "| Concept | Subject | From | Meaning |", "|---|---|---|---|",
  ...rows.filter((r) => r.kind === "N").map((r) => `| ${r.name} | ${subjectName.get(r.subject)} | ${r.area} | ${r.meaning} |`), "",
  "The candidates not taken: Department and Business Unit (kinds of Organization Unit), Employee (a kind of Employment), Job Classification (a Classification), Competency (a Skill), Workplace and Facility Assignment (a Site; an Assignment), Organizational Location (a Facility), Account (a Ledger Account), Ledger (the Chart of Accounts), Journal (Journal Entries in a Posting Batch). The folder is removed.", "");
// Every concept, by its current domain.
lines.push("## Every concept, by current domain", "");
const fate = (r) => ({ C: `common → ${subjectName.get(r.subject)}`, M: `merged into **${r.target}** → ${subjectName.get(r.subject)}`, S: `specializes ${r.target} → ${subjectName.get(r.subject)}`,
  K: `industry subject → ${subjectName.get(r.subject)}`, A: "application detail → named in the pattern", P: "modeling pattern → Data Migration" }[r.kind]);
for (const d of [...new Set(rows.filter((r) => r.kind !== "N").map((r) => r.domain))]) {
  const list = rows.filter((r) => r.domain === d);
  lines.push(`### ${domainTitle.get(d) || d} (${list.length})`, "", "| Concept | Fate |", "|---|---|", ...list.map((r) => `| ${r.was || r.name} | ${fate(r)}${r.was ? `, renamed **${r.name}**` : ""} |`), "");
}
lines.push("## Open questions", "",
  "1. **Merge names.** Where a merge creates a new common name (*Customer*, *Worker*, *Work Order*, *Price List*, *Usage Record*, *Site*, *Application*), is the name right?",
  "2. **Industry subjects.** Health Care, Insurance Coverage and Claims, Financial Accounts, Service Provisioning, Production, and Travel are owned by one industry each (Coverage is shared with health care). Keep them as subjects, or move what is not common into the patterns as application detail too?",
  "3. **New concepts.** The 13 concepts defined from Administration's candidates are written short; do they say what you mean (above)?",
  "", "Decided: the merge names, the industry subjects, and the renames stand as proposed; physical therapy leaves the model (what it shared with other domains stays, as aliases of the common concepts), and its pattern names its concepts.", "");
const out = path.join(repo, "docs", "subject-reclassification.md");
fs.writeFileSync(out, lines.join("\n"));
console.log(`${rows.length} concepts classified: ${["C", "M", "S", "K", "A", "P", "N"].map((k) => `${k} ${count(k)}`).join(", ")} → ${[...holds.values()].reduce((n, m) => n + m.size, 0)} concepts in ${SUBJECTS.length} subjects; ${families.length} cross-domain families. Written ${path.relative(repo, out)}`);
